package io.github.ktor_batterypack.validation.codegen.emit

import com.squareup.kotlinpoet.AnnotationSpec
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.ParameterSpec
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeName
import com.squareup.kotlinpoet.TypeSpec
import com.squareup.kotlinpoet.joinToCode
import io.github.ktor_batterypack.validation.codegen.ConstraintCall
import io.github.ktor_batterypack.validation.ksp.CodegenMode
import io.github.ktor_batterypack.validation.ksp.EntryMethod
import io.github.ktor_batterypack.validation.ksp.TypeMethod
import io.github.ktor_batterypack.validation.ksp.ValidatorModel
import io.github.ktor_batterypack.validation.ksp.ValueKind
import io.github.ktor_batterypack.validation.ksp.ValueModel
import io.github.ktor_batterypack.validation.ksp.jsonScalarTypeCheckMethodName

private const val VALIDATION_PACKAGE = "io.github.ktor_batterypack.validation"
private const val SELF_KEY = "$"

private val VALIDATION_CALL = ClassName(VALIDATION_PACKAGE, "ValidationCall")
private val VALIDATION_RESULT = ClassName(VALIDATION_PACKAGE, "ValidationResult")
private val CONSTRAINTS = ClassName(VALIDATION_PACKAGE, "Constraints")
private val JSON_TYPE_CHECKS = ClassName(VALIDATION_PACKAGE, "JsonTypeChecks")
private val JSON_NODE = ClassName("tools.jackson.databind", "JsonNode")
private val ARRAY_NODE = ClassName("tools.jackson.databind.node", "ArrayNode")
private val OBJECT_NODE = ClassName("tools.jackson.databind.node", "ObjectNode")
private val GENERATED = ClassName("javax.annotation.processing", "Generated")
private val CLOCK = ClassName("java.time", "Clock")

private val NESTED_KINDS = setOf(ValueKind.OBJECT, ValueKind.LIST, ValueKind.MAP)

class ValidatorEmitter {

    fun emit(model: ValidatorModel): FileSpec {
        val type = TypeSpec.classBuilder(model.implClassName)
            .addKdoc(
                "Validator implementation for [%T].\n\n" +
                    "NOTE: This class is auto generated by Ktor-Batterypack-Validation " +
                    "(https://github.com/kamil-perczynski/ktor-batterypack).\n" +
                    "Do not edit the class manually.\n",
                model.interfaceClassName
            )
            .addAnnotation(GENERATED)
            .primaryConstructor(
                FunSpec.constructorBuilder()
                    .addParameter(
                        ParameterSpec.builder("clock", CLOCK)
                            .defaultValue("%T.systemDefaultZone()", CLOCK)
                            .build()
                    )
                    .build()
            )
            .addProperty(PropertySpec.builder("clock", CLOCK, KModifier.PRIVATE).initializer("clock").build())
            .addSuperinterface(model.interfaceClassName)
            .addFunctions(model.entryMethods.map { method -> entryFunction(model.mode, method) })
            .addFunctions(model.typeMethods.map { method -> typeFunction(model.mode, method) })

        if (model.mode == CodegenMode.TYPED) {
            type.addAnnotation(
                AnnotationSpec.builder(Suppress::class).addMember("%S", "UNNECESSARY_SAFE_CALL").build()
            )
        }

        return FileSpec.builder(model.implClassName)
            .indent("    ")
            .addType(type.build())
            .build()
    }

    private fun entryFunction(mode: CodegenMode, method: EntryMethod): FunSpec {
        val code = CodeBlock.builder()
        code.addStatement("val call = %T(clock = clock)", VALIDATION_CALL)

        val validateWith = method.value.validateWith
        if (mode == CodegenMode.JSON) {
            addValue(code, mode, method.value, SELF_KEY, CodeBlock.of("%N", method.paramName), "call", nested = false)
        } else if (validateWith != null) {
            code.addStatement("%N(%N, call)", validateWith, method.paramName)
        }

        code.addStatement("val errors = call.%N()", finishMethod(method.value.kind))
        code.addStatement(
            "return if (errors != null) %T.invalid(%N, errors) else %T.valid(%N)",
            VALIDATION_RESULT,
            method.paramName,
            VALIDATION_RESULT,
            method.paramName
        )

        return FunSpec.builder(method.name)
            .addModifiers(KModifier.OVERRIDE)
            .addParameter(method.paramName, method.paramType)
            .returns(method.returnType)
            .addCode(code.build())
            .build()
    }

    private fun typeFunction(mode: CodegenMode, method: TypeMethod): FunSpec {
        val code = CodeBlock.builder()
        code.addStatement("if (%N == null) return", method.paramName)

        for (property in method.properties) {
            val source = if (mode == CodegenMode.TYPED) {
                CodeBlock.of("%N.%N", method.paramName, property.name)
            } else {
                CodeBlock.of("%N", method.paramName)
            }
            addValue(code, mode, property.value, property.key, source, "call", nested = property.value.kind in NESTED_KINDS)
        }

        val item = method.item
        if (item != null) {
            addItemLoop(code, mode, method, item)
        }

        for (additionalCall in method.additionalCalls) {
            code.addStatement("%N(%N, call)", additionalCall, method.paramName)
        }

        val modifier = if (method.declaredParamType != null) KModifier.OVERRIDE else KModifier.PRIVATE
        return FunSpec.builder(method.name)
            .addModifiers(modifier)
            .addParameter(method.paramName, method.declaredParamType ?: generatedParamType(mode, method).copy(nullable = true))
            .addParameter("call", VALIDATION_CALL)
            .addCode(code.build())
            .build()
    }

    private fun addItemLoop(code: CodeBlock.Builder, mode: CodegenMode, method: TypeMethod, item: ValueModel) {
        if (method.kind == ValueKind.MAP) {
            val entries = if (mode == CodegenMode.JSON) ".properties()" else ""
            code.beginControlFlow("for ((key, item) in %N%L)", method.paramName, entries)
            code.addStatement("val itemCall = call.nestedProperty(key)")
        } else {
            code.beginControlFlow("for (item in %N)", method.paramName)
            code.addStatement("val itemCall = call.listItem()")
        }

        addValue(code, mode, item, SELF_KEY, CodeBlock.of("item"), "itemCall", nested = false)
        code.addStatement("itemCall.%N()", finishMethod(item.kind))
        code.endControlFlow()
    }

    private fun addValue(
        code: CodeBlock.Builder,
        mode: CodegenMode,
        value: ValueModel,
        key: String,
        source: CodeBlock,
        call: String,
        nested: Boolean
    ) {
        val keyLiteral = KotlinLiteralRenderer.render(key)
        if (value.checkNotNull) {
            code.addStatement("%L(%L, %L, %N)", qualified(notNullCheck(mode)), keyLiteral, source, call)
        }

        val read = if (mode == CodegenMode.JSON) {
            CodeBlock.of("%L(%L, %L, %N)", qualified(jsonTypeCheck(value)), keyLiteral, source, call)
        } else {
            source
        }

        val body = valueBody(mode, value, key, call, nested)
        if (body.isEmpty()) {
            if (mode == CodegenMode.JSON) {
                code.addStatement("%L", read)
            }
            return
        }

        code.beginControlFlow("%L?.let", read)
        code.add(body)
        code.endControlFlow()
    }

    private fun valueBody(mode: CodegenMode, value: ValueModel, key: String, call: String, nested: Boolean): CodeBlock {
        val body = CodeBlock.builder()
        val bodyCall = if (nested) "itemCall" else call
        val constraintKey = KotlinLiteralRenderer.render(if (nested) SELF_KEY else key)

        if (nested) {
            body.addStatement("val itemCall = %N.nestedProperty(%L)", call, KotlinLiteralRenderer.render(key))
        }
        for (constraint in value.constraints) {
            body.addStatement("%L(%L, it, %N%L)", qualified(constraint.member), constraintKey, bodyCall, constraintArgs(constraint))
        }
        if (mode == CodegenMode.JSON && value.kind == ValueKind.ENUM) {
            val allowedValues = value.type.enumValues.map { enumValue -> CodeBlock.of("%S", enumValue) }.joinToCode(", ")
            body.addStatement(
                "%T.checkEnum(%L, it, %N, setOf(%L))",
                JSON_TYPE_CHECKS,
                constraintKey,
                bodyCall,
                allowedValues
            )
        }
        if (value.validateWith != null) {
            body.addStatement("%N(it, %N)", value.validateWith, bodyCall)
        }
        if (nested) {
            body.addStatement("itemCall.%N()", finishMethod(value.kind))
        }

        return body.build()
    }

    private fun constraintArgs(constraint: ConstraintCall): CodeBlock {
        if (constraint.args.isEmpty()) {
            return CodeBlock.of("")
        }
        return CodeBlock.of(", %L", KotlinLiteralRenderer.renderArgs(constraint.args))
    }

    private fun generatedParamType(mode: CodegenMode, method: TypeMethod): TypeName {
        if (mode == CodegenMode.TYPED) {
            return method.type.typeName
        }
        return when (method.kind) {
            ValueKind.LIST -> ARRAY_NODE
            ValueKind.OBJECT, ValueKind.MAP -> OBJECT_NODE
            ValueKind.SCALAR, ValueKind.ENUM -> JSON_NODE
        }
    }

    private fun notNullCheck(mode: CodegenMode): MemberName {
        val owner = if (mode == CodegenMode.JSON) JSON_TYPE_CHECKS else CONSTRAINTS
        return MemberName(owner, "checkNotNull")
    }

    private fun jsonTypeCheck(value: ValueModel): MemberName {
        val methodName = when (value.kind) {
            ValueKind.SCALAR -> jsonScalarTypeCheckMethodName(value.type.fqName)
                ?: throw IllegalArgumentException("Unsupported JSON type ${value.type.fqName}")
            ValueKind.ENUM -> "checkString"
            ValueKind.LIST -> "checkArray"
            ValueKind.OBJECT, ValueKind.MAP -> "checkObject"
        }
        return MemberName(JSON_TYPE_CHECKS, methodName)
    }

    private fun qualified(member: MemberName): CodeBlock {
        val enclosingClassName = member.enclosingClassName ?: return CodeBlock.of("%M", member)
        return CodeBlock.of("%T.%N", enclosingClassName, member.simpleName)
    }

    private fun finishMethod(kind: ValueKind): String {
        return if (kind == ValueKind.LIST) "finishList" else "finishObject"
    }
}
